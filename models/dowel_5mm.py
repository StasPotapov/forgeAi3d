"""Мебельный дюбель (анкер) под шуруп 3.5x15 в отверстие 5 мм.

Распорная втулка. Работают три вещи одновременно:

* сквозная прорезь вдоль тела — половинки расходятся, когда шуруп идёт внутрь,
  и распирают дюбель в отверстии; она же даёт телу сжаться при забивании,
  поэтому зубцы можно делать заметно выше номинала;
* кольцевые зубцы — держат от выдёргивания;
* продольные рёбра — держат от проворачивания. Кольцевые зубцы против кручения
  не работают вообще (тело осесимметричное, цепляться нечем) — из-за этого
  первая версия крутилась в отверстии вместе с шурупом и не давала его вкрутить.

Печатать стоя (ось дюбеля вертикально), как деталь и построена.
"""
from math import radians, tan

from build123d import *

from forge import clearance, export_all, wall

MAT = "PETG"          # вязкий: держит резьбу шурупа и не лопается от распора

# --- размеры чужого железа: сказаны пользователем, не выдуманы ---
HOLE_D     = 5.0      # отверстие в мебели
HOLE_DEPTH = 11.0     # рабочая глубина посадки; укорочено с 15 — по примерке было длинно
SCREW_D    = 3.5      # диаметр резьбовой части шурупа
SCREW_L    = 15.0     # длина шурупа
HEAD_D     = 7.0      # шляпка — фланец делаем заведомо меньше, чтобы она его накрыла

# --- что крутится по итогам печати ---
PILOT_TOP  = 2.9      # внутреннее отверстие сверху; больше => шуруп идёт легче,
PILOT_BOT  = 2.5      # снизу уже — шуруп идёт всё туже и распирает втулку.
                      # Оба подняты на 0.3 против первой версии: там шуруп не нарезал
                      # резьбу, а срывал дюбель с места.
BARB_OVER  = 0.35     # выступ зубца за тело, на сторону (было 0.20 — не держало)
BARB_RISE  = 1.0      # высота конуса зубца; меньше при том же выступе = круче заход
BARB_FLAT  = 0.9      # цилиндрический поясок на вершине: зубец-клин сходится в ноль
                      # толщиной, печатается ниткой и сминается о дерево
BARB_PITCH = 2.6      # шаг зубцов
BARB_FIRST = 2.0      # где начинается первый зубец
RIB_COUNT  = 4        # продольные рёбра против проворота
RIB_OVER   = 0.45     # выступ ребра за тело, на сторону: врезается в стенку отверстия
RIB_W      = 1.3      # ширина ребра у основания
RIB_TIP    = 0.45     # ширина по вершине: одна линия периметра, острее не напечатать
RIB_ROOT   = 0.3      # насколько основание ребра утоплено в тело (надёжное сращивание)
RIB_START  = 45       # первое ребро под 45°: рёбра идут мимо прорези, по два на половинку
FLANGE_D   = 6.0      # бортик: не даёт провалиться, прячется под шляпкой 7 мм
FLANGE_H   = 0.7
LEAD_IN    = 0.5      # заходная фаска снизу, по радиусу (её режет нож, см. lead_pts)
CHAMFER_TOP = 0.3     # заходная фаска под шуруп сверху
SLOT_W     = 0.7      # ширина прорези у самого пилотного отверстия
SLOT_ANG   = 20.0     # раскрытие клина прорези: наружу щель расходится радиально.
                      # Прямая щель постоянной ширины резала бы цилиндр почти по
                      # касательной и оставляла по краям острые лезвия в ноль толщиной
SLOT_TOP   = HOLE_DEPTH - 1.0   # докуда режет; выше — перемычка, она держит половинки

RIB_ANGLES = tuple(RIB_START + i * 360 / RIB_COUNT for i in range(RIB_COUNT))

BODY_R = (HOLE_D - 2 * clearance(MAT, "press")) / 2   # запрессовка в 5 мм
BARB_R = BODY_R + BARB_OVER
RIB_R  = BODY_R + RIB_OVER
FLANGE_RISE = FLANGE_D / 2 - BODY_R                   # конус под фланцем ровно 45°
TOP_Z = HOLE_DEPTH + FLANGE_RISE + FLANGE_H

_min_wall = BODY_R - PILOT_TOP / 2
assert _min_wall >= wall(2), f"стенка {_min_wall:.2f} тоньше двух периметров {wall(2)}"
assert FLANGE_D < HEAD_D, "бортик должен прятаться под шляпкой шурупа"
assert SLOT_TOP < HOLE_DEPTH, "прорезь на всю длину развалит дюбель на две половинки"
assert SLOT_W >= wall(1), f"прорезь {SLOT_W} уже линии периметра — слайсер её заплавит"
assert RIB_TIP >= wall(1), f"вершина ребра {RIB_TIP} тоньше линии периметра {wall(1)}"
SLOT_OUT = 2 * BODY_R * tan(radians(SLOT_ANG / 2))   # ширина щели у стенки отверстия
assert SLOT_OUT >= SLOT_W, "клин уже полосы — наружу щель выйдет острыми лезвиями"

# Профиль в осевом сечении: (радиус, высота), обход по внешнему контуру снизу вверх.
# Заходной фаски у дна здесь нет намеренно: её срезает общий нож захода, а нарисовать
# её ещё и в профиле нельзя — совпадающие грани при вычитании ломают тесселяцию.
pts: list[tuple[float, float]] = [
    (PILOT_BOT / 2, 0.0),          # дно, внутренняя кромка
    (BODY_R, 0.0),                 # дно, наружная кромка
]

z = BARB_FIRST
while z + BARB_RISE + BARB_FLAT <= HOLE_DEPTH - 1.0:
    pts += [
        (BODY_R, z),                           # подошва зубца
        (BARB_R, z + BARB_RISE),               # конец пологого захода
        (BARB_R, z + BARB_RISE + BARB_FLAT),   # поясок: им зубец и стоит в дереве
        (BODY_R, z + BARB_RISE + BARB_FLAT),   # ступенька вниз — держит от выдёргивания
    ]
    z += BARB_PITCH

pts += [
    (BODY_R, HOLE_DEPTH),
    (FLANGE_D / 2, HOLE_DEPTH + FLANGE_RISE),   # конус 45°, печатается без поддержки
    (FLANGE_D / 2, TOP_Z),
    (PILOT_TOP / 2 + CHAMFER_TOP, TOP_Z),
    (PILOT_TOP / 2, TOP_Z - CHAMFER_TOP),       # дальше замыкание вниз = конус отверстия
]

# сечение ребра в плане: трапеция от утопленного основания к плоской вершине
rib_pts = [
    (BODY_R - RIB_ROOT, -RIB_W / 2),
    (BODY_R - RIB_ROOT,  RIB_W / 2),
    (RIB_R,              RIB_TIP / 2),
    (RIB_R,             -RIB_TIP / 2),
]

# нож прорези в плане: центральная полоса плюс два радиальных клина. Полоса держит
# ширину щели у пилота, клинья выводят её наружу гранями, нормальными к поверхности
KNIFE_R = RIB_R + 1.0
wedge_pts = [
    (0.0, 0.0),
    (KNIFE_R,  KNIFE_R * tan(radians(SLOT_ANG / 2))),
    (KNIFE_R, -KNIFE_R * tan(radians(SLOT_ANG / 2))),
]

# нож захода: срезает конусом 45° всё, что торчит у самого дна, — иначе рёбра
# начинались бы вертикальной ступенькой и дюбель не наживить в отверстие
LEAD_R = RIB_R + 0.5
lead_pts = [
    (BODY_R - LEAD_IN, 0.0),
    (LEAD_R, 0.0),
    (LEAD_R, LEAD_R - (BODY_R - LEAD_IN)),
]

with BuildPart() as dowel:
    with BuildSketch(Plane.XZ):
        with BuildLine():
            Polyline(*pts, close=True)
        make_face()
    revolve(axis=Axis.Z)

    with BuildSketch(Plane.XY):
        with Locations(*[Rot(0, 0, a) for a in RIB_ANGLES]):
            Polygon(*rib_pts, align=None)
    extrude(amount=HOLE_DEPTH)

    with BuildSketch(Plane.XZ):
        with BuildLine():
            Polyline(*lead_pts, close=True)
        make_face()
    revolve(axis=Axis.Z, mode=Mode.SUBTRACT)

    # нож прорези опущен ниже дна: грань в плоскости дна детали даёт ту же
    # негерметичную сетку, что и совпадающая фаска
    with BuildSketch(Plane.XY.offset(-1.0)):
        Rectangle(SLOT_W, 2 * KNIFE_R)
        with Locations(*[Rot(0, 0, a) for a in (90, 270)]):
            Polygon(*wedge_pts, align=None)
    extrude(amount=SLOT_TOP + 1.0, mode=Mode.SUBTRACT)

paths = export_all(dowel.part, "dowel_5mm", material=MAT)
print(f"дюбель {HOLE_D} мм под шуруп {SCREW_D}x{SCREW_L}: "
      f"высота {TOP_Z:.2f}, посадка {HOLE_DEPTH}, стенка {_min_wall:.2f}, "
      f"Ø по зубцам {2 * BARB_R:.2f}, Ø по рёбрам {2 * RIB_R:.2f}, "
      f"прорезь {SLOT_W}..{SLOT_OUT:.2f} x {SLOT_TOP}")
for k, v in paths.items():
    print(f"  {k}: {v}")
